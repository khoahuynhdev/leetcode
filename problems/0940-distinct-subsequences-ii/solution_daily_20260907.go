package main

// 0940. Distinct Subsequences II
// https://leetcode.com/problems/distinct-subsequences-ii/
//
// Approach: dynamic programming with one bucket per lowercase letter.
//
// dp[c] holds the number of distinct non-empty subsequences of the prefix
// processed so far that END with the character c. Every distinct subsequence
// ends in exactly one letter, so the 26 buckets partition the answer set and
// the result is simply their sum.
//
// When we read a character c, the distinct subsequences of the new prefix
// ending in c are exactly {t + c} for t empty or any distinct subsequence of
// the prefix, giving:
//
//	dp[c] = (sum of all dp) + 1
//
// The assignment (rather than +=) is what removes duplicates: any subsequence
// ending in c that was already counted is regenerated by this formula, so
// overwriting attributes each distinct string to the LAST occurrence of its
// final character and counts it exactly once.
//
// Time: O(26n). Space: O(1).

const distinctSubseqIIMod = 1_000_000_007

func distinctSubseqII(s string) int {
	// dp[c] = count of distinct subsequences seen so far ending in 'a'+c.
	var dp [26]int

	for i := 0; i < len(s); i++ {
		total := 0
		for _, count := range dp {
			total = (total + count) % distinctSubseqIIMod
		}
		// Overwrite, do not accumulate: the old value is already included
		// in total, and re-adding it would double count.
		dp[s[i]-'a'] = (total + 1) % distinctSubseqIIMod
	}

	answer := 0
	for _, count := range dp {
		answer = (answer + count) % distinctSubseqIIMod
	}
	return answer
}
